<?php
check( 'identical page → zero hunks',
	array() === Tumils_MSN_Differ::diff( fixture( 'base.html' ), fixture( 'base.html' ) ) );

check( 'noise-only pair → zero hunks',
	array() === Tumils_MSN_Differ::diff( fixture( 'base.html' ), fixture( 'base-noise.html' ) ) );

$tumils_msn_h = Tumils_MSN_Differ::diff( fixture( 'base.html' ), fixture( 'base-migrated.html' ) );
check( 'migrated → exactly one hunk', 1 === count( $tumils_msn_h ) );
check( 'migrated hunk is a class change', 'classes' === $tumils_msn_h[0]['type'] );
check( 'migrated hunk is structural', 'structural' === $tumils_msn_h[0]['severity'] );
check( 'migrated hunk names the new class', 'et_flex_row' === $tumils_msn_h[0]['after'] );
check( 'migrated hunk path reaches the row', false !== strpos( $tumils_msn_h[0]['path'], 'et_pb_row' ) );

$tumils_msn_t = Tumils_MSN_Differ::diff( fixture( 'base.html' ), fixture( 'base-text.html' ) );
check( 'text change → exactly one hunk', 1 === count( $tumils_msn_t ) );
check( 'text hunk is cosmetic text', 'text' === $tumils_msn_t[0]['type'] && 'cosmetic' === $tumils_msn_t[0]['severity'] );
check( 'text hunk carries before/after', 'Hello world' === $tumils_msn_t[0]['before'] && 'Hello there' === $tumils_msn_t[0]['after'] );

$tumils_msn_r = Tumils_MSN_Differ::diff( fixture( 'base.html' ), fixture( 'base-removed.html' ) );
check( 'removed column → exactly one hunk', 1 === count( $tumils_msn_r ) );
check( 'removed hunk is structural removal', 'removed' === $tumils_msn_r[0]['type'] && 'structural' === $tumils_msn_r[0]['severity'] );
check( 'removed hunk shows the lost markup', false !== strpos( $tumils_msn_r[0]['before'], 'Side' ) );

$tumils_msn_rf = Tumils_MSN_Differ::diff( fixture( 'base.html' ), fixture( 'base-removed-first.html' ) );
check( 'removed FIRST column → exactly one hunk', 1 === count( $tumils_msn_rf ) );
check( 'removed-first hunk is structural removal', 'removed' === $tumils_msn_rf[0]['type'] && 'structural' === $tumils_msn_rf[0]['severity'] );
check( 'removed-first hunk names the lost column, not the survivor',
	false !== strpos( $tumils_msn_rf[0]['before'], 'Hello world' ) && false === strpos( $tumils_msn_rf[0]['before'], 'Side' ) );

// Task 11: D4->D5 blurb-wrapper consolidation (icon+text wrappers merge into
// one div). Without unwrapping, the differ's positional alignment mis-pairs
// the icon wrapper with the merged text wrapper and reports a cluster of
// spurious class/remove/add hunks around the one real change (icon lost).
$tumils_msn_b = Tumils_MSN_Differ::diff(
	fixture( 'noise-divi5-blurb-wrapper-consolidation-before.html' ),
	fixture( 'noise-divi5-blurb-wrapper-consolidation-after.html' )
);
check( 'blurb wrapper consolidation -> exactly one hunk (the icon, not a restructuring cluster)',
	1 === count( $tumils_msn_b ) );
check( 'blurb wrapper hunk is the lost icon markup',
	isset( $tumils_msn_b[0] ) && 'removed' === $tumils_msn_b[0]['type'] && false !== strpos( $tumils_msn_b[0]['before'], 'et-pb-icon' ) );

// Final review F1: the differ used to compare only class and style, so a
// swapped image src produced a content_hash change with ZERO hunks — which the
// report then downgraded to "Migration verified clean". Attributes other than
// class/style are diffed as one aggregated hunk per element.
$tumils_msn_a = Tumils_MSN_Differ::diff(
	fixture( 'real-img-src-change-before.html' ),
	fixture( 'real-img-src-change-after.html' )
);
check( 'changed img src -> exactly one hunk (attributes aggregated per element)',
	1 === count( $tumils_msn_a ) );
check( 'img src hunk is type attrs, cosmetic',
	isset( $tumils_msn_a[0] ) && 'attrs' === $tumils_msn_a[0]['type'] && 'cosmetic' === $tumils_msn_a[0]['severity'] );
check( 'img src hunk carries both src values',
	isset( $tumils_msn_a[0] )
	&& false !== strpos( $tumils_msn_a[0]['before'], 'team-photo.jpg' )
	&& false !== strpos( $tumils_msn_a[0]['after'], 'team-photo-2.jpg' ) );
check( 'img attrs hunk aggregates the dropped width onto the before side only',
	isset( $tumils_msn_a[0] )
	&& false !== strpos( $tumils_msn_a[0]['before'], 'width="800"' )
	&& false === strpos( $tumils_msn_a[0]['after'], 'width=' ) );
check( 'img attrs hunk leaves unchanged attributes (alt, height) out of both sides',
	isset( $tumils_msn_a[0] )
	&& false === strpos( $tumils_msn_a[0]['before'], 'alt=' )
	&& false === strpos( $tumils_msn_a[0]['after'], 'height=' ) );

// Same review, second half: ids are regenerated by the D4->D5 migration. The
// loose gap signature keys on tag+id, so on its own an id change makes the
// element fail to pair and explode into a structural remove+add ("a section
// vanished and a different one appeared"). The content tier catches it first
// and keeps it one attrs hunk.
//
// The `id` is the ONLY thing that differs here, deliberately. This fixture used
// to change the row's text as well ('Alpha' -> 'Alpha changed'), which made it
// a test of two variables at once and, from the differ's side, literally
// indistinguishable from the content-swap fixture below — same tag, different
// id, different text. See that fixture for how the ambiguity is resolved.
$tumils_msn_id_before = '<html><body><div class="et_pb_section"><div id="et_pb_row_0" class="et_pb_row"><p>Alpha</p></div><div id="keep" class="et_pb_row"><p>Beta</p></div></div></body></html>';
$tumils_msn_id_after  = '<html><body><div class="et_pb_section"><div id="divi-row-0" class="et_pb_row"><p>Alpha</p></div><div id="keep" class="et_pb_row"><p>Beta</p></div></div></body></html>';
$tumils_msn_i = Tumils_MSN_Differ::diff( $tumils_msn_id_before, $tumils_msn_id_after );
$tumils_msn_i_attrs = array_values( array_filter( $tumils_msn_i, function ( $h ) { return 'attrs' === $h['type']; } ) );
$tumils_msn_i_struct = array_values( array_filter( $tumils_msn_i, function ( $h ) { return 'removed' === $h['type'] || 'added' === $h['type']; } ) );
check( 'changed element id -> exactly one attrs hunk, no removed/added pair',
	1 === count( $tumils_msn_i_attrs ) && 0 === count( $tumils_msn_i_struct ) );
check( 'id-change hunk carries both ids',
	isset( $tumils_msn_i_attrs[0] )
	&& false !== strpos( $tumils_msn_i_attrs[0]['before'], 'et_pb_row_0' )
	&& false !== strpos( $tumils_msn_i_attrs[0]['after'], 'divi-row-0' ) );

// Fix round 2, A: the counter-case to the id-change test above. Tag-only gap
// pairing bought id tolerance at the cost of pairing ANY two same-tag elements,
// so a row whose entire content was replaced degraded from a structural
// removed+added pair into a cosmetic attrs+text pair — the differ claiming a
// wholesale content swap was a tweak. Two-tier pairing (content first, then
// tag#id) keeps this one structural: neither the content nor the id matches.
$tumils_msn_swap = Tumils_MSN_Differ::diff(
	'<html><body><div class="et_pb_row" id="row-a"><p>Testimonial: Great service, highly recommend!</p></div></body></html>',
	'<html><body><div class="et_pb_row" id="row-b"><p>Pricing: Basic plan and Pro plan.</p></div></body></html>'
);
$tumils_msn_swap_types = array_column( $tumils_msn_swap, 'type' );
check( 'content swap w/ new ids → removed+added',
	in_array( 'removed', $tumils_msn_swap_types, true ) && in_array( 'added', $tumils_msn_swap_types, true ) );
check( 'content swap w/ new ids → structural',
	$tumils_msn_swap === array_filter( $tumils_msn_swap, function ( $h ) { return 'structural' === $h['severity']; } ) );
check( 'content swap w/ new ids → no cosmetic text downgrade',
	! in_array( 'text', $tumils_msn_swap_types, true ) );

// Pinning the accepted limit of the two-tier rule, so it is a tested decision
// rather than an unnoticed side effect. When BOTH the id and the text change,
// neither tier can vouch for identity and the pair is reported structurally —
// even if a human would have called the text edit minor. The differ has no
// similarity metric and deliberately gains none here: guessing "close enough"
// is how a replaced section gets waved through as a tweak, and over-reporting a
// hand-edited paragraph is the survivable half of that trade.
$tumils_msn_both = Tumils_MSN_Differ::diff(
	'<html><body><div class="et_pb_section"><div id="et_pb_row_0" class="et_pb_row"><p>Alpha</p></div><div id="keep" class="et_pb_row"><p>Beta</p></div></div></body></html>',
	'<html><body><div class="et_pb_section"><div id="divi-row-0" class="et_pb_row"><p>Alpha changed</p></div><div id="keep" class="et_pb_row"><p>Beta</p></div></div></body></html>'
);
$tumils_msn_both_types = array_column( $tumils_msn_both, 'type' );
check( 'id AND text both change → structural removed+added, never a silent downgrade',
	in_array( 'removed', $tumils_msn_both_types, true ) && in_array( 'added', $tumils_msn_both_types, true ) );
check( 'id+text change leaves the untouched sibling row alone', 2 === count( $tumils_msn_both ) );

// Fix round 2, C: the contract Tumils_MSN_Compare::compare_batch relies on to tell a
// stale stored hash from a real-but-unlocalizable change. diff() returns zero
// hunks in BOTH cases, so the caller re-checks the canonicals — which only
// works if a genuinely-differing pair can still yield zero hunks. It can: a
// capture whose <body> did not parse has nothing to walk. That is the case the
// synthetic 'opaque' hunk exists for, and it must stay reachable, or the
// stale-hash branch would swallow real changes instead of just stale hashes.
check( 'unparseable side → zero hunks while canonicals genuinely differ (opaque case stays reachable)',
	array() === Tumils_MSN_Differ::diff( fixture( 'base.html' ), '' )
	&& Tumils_MSN_Normalizer::canonical( fixture( 'base.html' ) ) !== Tumils_MSN_Normalizer::canonical( '' ) );

// Fix round 3, item 1: identity strength must be honoured in order. With the
// content tier running first, any gap where BOTH tiers could pair had the weak
// signal (a text fingerprint) overrule stable ids — so the differ invented an
// id rename that never happened and blamed the wrong row for a deletion.
// Truth here: r1's text was edited, r2 was deleted.
$tumils_msn_tri = Tumils_MSN_Differ::diff(
	'<html><body><div id="main" class="et_pb_section"><div id="r0" class="et_pb_row"><p>Content 0</p></div><div id="r1" class="et_pb_row"><p>Content 1</p></div><div id="r2" class="et_pb_row"><p>Content 2</p></div></div></body></html>',
	'<html><body><div id="main" class="et_pb_section"><div id="r0" class="et_pb_row"><p>Content 0</p></div><div id="r1" class="et_pb_row"><p>Content 2</p></div></div></body></html>'
);
$tumils_msn_tri_types = array_unique( array_column( $tumils_msn_tri, 'type' ) );
sort( $tumils_msn_tri_types );
check( 'id-stable edit + sibling delete → exactly {removed, text}',
	array( 'removed', 'text' ) === array_values( $tumils_msn_tri_types ) );
check( 'the deleted row (r2) is the one reported removed',
	false !== strpos( implode( '', array_column( $tumils_msn_tri, 'before' ) ), 'id="r2"' ) );
check( 'the surviving row (r1) is never reported removed',
	false === strpos( implode( '', array_column( array_values( array_filter( $tumils_msn_tri, function ( $h ) { return 'removed' === $h['type']; } ) ), 'before' ) ), 'id="r1"' ) );
check( 'no invented id rename', ! in_array( 'attrs', array_column( $tumils_msn_tri, 'type' ), true ) );

// Same defect, second face: two rows keep their ids and swap contents. Pairing
// on the text first married each row to the OTHER one, producing a fictional
// id rename plus a structural remove/add. Ids are stable — this is two edits.
$tumils_msn_rot = Tumils_MSN_Differ::diff(
	'<html><body><div id="a" class="et_pb_row"><p>Hello</p></div><div id="b" class="et_pb_row"><p>World</p></div></body></html>',
	'<html><body><div id="a" class="et_pb_row"><p>World</p></div><div id="b" class="et_pb_row"><p>Hello</p></div></body></html>'
);
check( 'id-stable content rotation → text hunks only',
	array( 'text' ) === array_values( array_unique( array_column( $tumils_msn_rot, 'type' ) ) ) );
check( 'id-stable content rotation → nothing structural',
	array() === array_filter( $tumils_msn_rot, function ( $h ) { return 'structural' === $h['severity']; } ) );
